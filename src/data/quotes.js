export function getRandomQuote(index) {
  if (typeof index === "number") {
    return COMFORT_QUOTES[index % COMFORT_QUOTES.length];
  }
  return COMFORT_QUOTES[Math.floor(Math.random() * COMFORT_QUOTES.length)];
}
