export async function analyzePostEmotionsLocally(postContent, tagId) {
  // Simulate natural brief reflective pause (600ms)
  await new Promise((resolve) => setTimeout(resolve, 600));

  const text = postContent || "";
  const _tag = EMOTIONAL_TAGS.find((t) => t.id === tagId) || EMOTIONAL_TAGS[0];

  // Rotate counter for response variety
  responseCounter++;

  // Determine which emotion block to use
  let responseSet;

  if (tagId === "future-anxiety" || matchesAny(text, ["خوف", "مستقبل", "رعب", "قلق", "مجهول", "الغد"])) {
    responseSet = RESPONSES["future-anxiety"];
  } else if (tagId === "silent-grief" || matchesAny(text, ["غصّة", "غصة", "رحيل", "ألم", "حزن", "تبكي", "بكاء", "دموع", "يبكي"])) {
    responseSet = RESPONSES["silent-grief"];
  } else if (tagId === "disappointment" || matchesAny(text, ["خيبة", "خذلان", "تغير", "غدر", "انكسر", "خُنت", "خان"])) {
    responseSet = RESPONSES["disappointment"];
  } else if (tagId === "longing" || tagId === "departed-loved-ones" || matchesAny(text, ["اشتياق", "حنين", "أشتاق", "نشتاق", "ذكرى", "ذكراهم"])) {
    responseSet = RESPONSES["longing"];
  } else if (tagId === "soul-exhaustion" || matchesAny(text, ["تعب", "إرهاق", "منهك", "طاقتي", "تعبت", "أتعبت", "مرهق"])) {
    responseSet = RESPONSES["soul-exhaustion"];
  } else if (tagId === "departed-loved-ones" || matchesAny(text, ["رحلوا", "فقدان", "موت", "مات", "توفي", "غاب", "فراق"])) {
    responseSet = RESPONSES["departed-loved-ones"];
  } else if (tagId === "faltering-hope" || matchesAny(text, ["أمل", "صبر", "انتظار", "فرج", "أتمسك", "أرجو", "علّ"])) {
    responseSet = RESPONSES["faltering-hope"];
  } else if (tagId === "path-confusion" || matchesAny(text, ["حيرة", "ضياع", "طريق", "غربة", "غريب", "حائرة", "لا أعرف"])) {
    responseSet = RESPONSES["path-confusion"];
  } else if (tagId === "unspoken-choke" || matchesAny(text, ["صمت", "كلام", "كلمة", "خنقت", "خنق", "محبوس", "عجزت"])) {
    responseSet = RESPONSES["unspoken-choke"];
  } else {
    responseSet = DEFAULT_RESPONSE;
  }

  // Select response by rotating through available options
  const idx = responseCounter % responseSet.length;
  const selected = responseSet[idx];

  return {
    emotionTone: selected.tone,
    tenderReflection: selected.reflection,
    gentleWhisper: selected.whisper
  };
}

function matchesAny(text, keywords) {
  const lower = text.toLowerCase();
  return keywords.some((kw) => lower.includes(kw));
}
